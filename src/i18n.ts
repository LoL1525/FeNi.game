const ru = Object.fromEntries(Object.entries(en).map(([russian, english]) => [english, russian]))
Object.assign(ru, {
  Common: 'Обычная',
  Uncommon: 'Необычная',
  Rare: 'Редкая',
  Epic: 'Эпическая',
  Legendary: 'Легендарная',
  Anomalous: 'Аномальная',
})

export function t(language: Language, text: string): string {
  return language === 'ru' ? (ru[text] ?? text) : (en[text] ?? text)
}

export function translateTemplate(language: Language, text: string, ...values: (string | number)[]) {
  let translated = t(language, text)
  for (const [index, value] of values.entries()) translated = translated.replace(`{${index}}`, String(value))
  return translated
}
